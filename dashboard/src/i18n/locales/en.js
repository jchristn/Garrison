// Lowercase a title for use mid-sentence, keeping acronyms (MCP, API, A2A, ID, URL) intact.
const midSentence = (text) =>
  text
    .split(' ')
    .map((word) => (/^[A-Z0-9]{2,}s?$/.test(word) ? word : word.toLowerCase()))
    .join(' ');

