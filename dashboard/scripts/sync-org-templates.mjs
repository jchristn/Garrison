// Copies the example manifests the organization templates apply (LP3.8) into src/utils/orgTemplateManifests.js.
// The dashboard image is built from dashboard/ alone, so it cannot read examples/ at run time. Run this after
// changing a file under examples/autonomous/gerbil or examples/autonomous/site-reliability-org:
//
//   node scripts/sync-org-templates.mjs
//
// src/tests/orgTemplates.test.js fails while the copy and the examples differ.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const examples = join(here, '..', '..', 'examples', 'autonomous');

/** Each export: its name and the example files it joins, in apply order. */
export const TEMPLATE_FILES = {
  GERBIL_MANIFEST: ['gerbil/gerbil.yaml', 'gerbil/fake-harness.yaml', 'gerbil/scenarios/healthy.yaml'],
  SITE_RELIABILITY_MANIFEST: ['site-reliability-org/org.yaml', 'site-reliability-org/fake-harness.yaml']
};

/** The files of one export joined as one multi-document manifest, the way the example READMEs apply them. */
export function joined(files) {
  return files.map((f) => readFileSync(join(examples, f), 'utf8').replace(/\s+$/, '')).join('\n---\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const lines = [
    '// Generated by scripts/sync-org-templates.mjs from examples/autonomous. Do not edit by hand: change the example and',
    '// run the script again. The organization templates (LP3.8) apply these through the manifest apply route.',
    ''
  ];
  for (const [name, files] of Object.entries(TEMPLATE_FILES)) {
    lines.push(`/** ${files.map((f) => `examples/autonomous/${f}`).join(', ')}. */`);
    lines.push(`export const ${name} = ${JSON.stringify(joined(files))};`);
    lines.push('');
  }
  writeFileSync(join(here, '..', 'src', 'utils', 'orgTemplateManifests.js'), lines.join('\n'));
}
