namespace Test.Shared.Infrastructure
{
    using System;
    using System.Linq;
    using System.Collections.Generic;
    using System.Threading;
    using System.Threading.Tasks;
    using Garrison.Core.Serialization;
    using WatsonWebserver;
    using WatsonWebserver.Core;

    /// <summary>Temporary OpenAI-compatible endpoint for real streaming HTTP and MCP loop tests.</summary>
    public class FakeProviderServer : IDisposable
    {
        private readonly Webserver _Server;
        private int _Requests;
        private bool _Disposed;
        /// <summary>Random loopback endpoint.</summary>
        public string Endpoint { get; }
        /// <summary>Request count.</summary>
        public int Requests { get { return Volatile.Read(ref _Requests); } }
        /// <summary>Last typed request.</summary>
        public FakeProviderRequest? LastRequest { get; private set; } = null;
        /// <summary>Generate a function call before answering. Default false.</summary>
        public bool UseTool { get; set; } = false;
        /// <summary>Select a tool by a description fragment.</summary>
        public string ToolDescription { get; set; } = "List the Garrison agents";
        /// <summary>Arguments generated by the fixture model.</summary>
        public string ToolArguments { get; set; } = "{}";
        /// <summary>HTTP failure status, or 200 for success.</summary>
        public int HttpStatus { get; set; } = 200;
        /// <summary>First requests that return 429. Default zero.</summary>
        public int RetryResponses { get; set; } = 0;
        /// <summary>Response delay in milliseconds. Default zero.</summary>
        public int DelayMs { get; set; } = 0;
        /// <summary>Fixture answers by model request; the last answer repeats.</summary>
        public List<string> Answers { get; set; } = new List<string> { "fixture answer" };
        /// <summary>Use length instead of stop to simulate incomplete generation.</summary>
        public bool Truncated { get; set; } = false;
        /// <summary>Start an isolated fixture endpoint.</summary>
        public FakeProviderServer()
        {
            int port = TestServerHost.FreePort();
            Endpoint = "http://127.0.0.1:" + port;
            _Server = new Webserver(new WebserverSettings { Hostname = "127.0.0.1", Port = port }, NotFoundAsync);
            _Server.Routes.PreAuthentication.Static.Add(HttpMethod.POST, "/v1/chat/completions", CompleteAsync);
            _Server.Start();
        }
        /// <inheritdoc />
        public void Dispose() { Dispose(true); GC.SuppressFinalize(this); }
        /// <summary>Stop the fixture listener.</summary>
        /// <param name="disposing">Whether to dispose managed resources.</param>
        protected virtual void Dispose(bool disposing)
        {
            if (_Disposed) return;
            if (disposing) _Server.Dispose();
            _Disposed = true;
        }
        private async Task CompleteAsync(HttpContextBase http)
        {
            int request = Interlocked.Increment(ref _Requests);
            LastRequest = Serializer.Deserialize<FakeProviderRequest>(http.Request.DataAsString);
            if (DelayMs > 0) await Task.Delay(DelayMs, http.Token).ConfigureAwait(false);
            if (HttpStatus != 200 || request <= RetryResponses)
            {
                http.Response.StatusCode = request <= RetryResponses ? 429 : HttpStatus;
                http.Response.ContentType = "application/json";
                await http.Response.Send("{\"error\":{\"message\":\"fixture failure\"}}").ConfigureAwait(false);
                return;
            }
            string body;
            if (UseTool && LastRequest?.Messages.Any(m => m.Role == "tool") != true)
            {
                FakeProviderTool? tool = LastRequest?.Tools.FirstOrDefault(t => t.Function.Description.Contains(ToolDescription, StringComparison.Ordinal));
                body = Chunk(new { tool_calls = new[] { new { index = 0, id = "fixture-call", type = "function", function = new { name = tool?.Function.Name ?? "unknown-function", arguments = ToolArguments } } } }, null)
                    + Chunk(new { }, "tool_calls");
            }
            else
            {
                string answer = Answers[Math.Min(request - 1, Answers.Count - 1)];
                int split = answer.Length / 2;
                body = Chunk(new { content = answer.Substring(0, split) }, null) + Chunk(new { content = answer.Substring(split) }, Truncated ? "length" : "stop");
            }
            body += "data: " + Serializer.Serialize(new { id = "fixture-response", @object = "chat.completion.chunk", model = "served-fixture-model", choices = Array.Empty<object>(), usage = new { prompt_tokens = 11, completion_tokens = 7, total_tokens = 18, prompt_tokens_details = new { cached_tokens = 3 }, completion_tokens_details = new { reasoning_tokens = 2 } } }) + "\n\ndata: [DONE]\n\n";
            http.Response.StatusCode = 200;
            http.Response.ContentType = "text/event-stream";
            await http.Response.Send(body).ConfigureAwait(false);
        }
        private static string Chunk(object delta, string? finish)
        {
            return "data: " + Serializer.Serialize(new { id = "fixture-response", @object = "chat.completion.chunk", created = 1, model = "served-fixture-model", choices = new[] { new { index = 0, delta, finish_reason = finish } } }) + "\n\n";
        }
        private static async Task NotFoundAsync(HttpContextBase http) { http.Response.StatusCode = 404; await http.Response.Send().ConfigureAwait(false); }
    }
}
