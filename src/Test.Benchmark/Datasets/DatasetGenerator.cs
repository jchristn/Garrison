namespace Garrison.Benchmark.Datasets
{
    using System;
    using System.Collections.Generic;
    using System.Globalization;
    using System.IO;
    using System.Linq;
    using System.Text;
    using System.Text.Json;
    using System.Text.RegularExpressions;
    using Garrison.Benchmark.Client;

    /// <summary>
    /// Builds the committed datasets from their committed sources. The synthetic dataset is generated with a seeded
    /// random number generator, so the same sources always give byte-identical output. The live dataset is a frozen
    /// snapshot of the repository's shipped manifests (examples/ and k8s/base/manifests/), substituted the way the
    /// bootstrap Job would. Stateless and thread-safe.
    /// </summary>
    public static class DatasetGenerator
    {
        #region Public-Methods

        /// <summary>
        /// Build the synthetic dataset.
        /// </summary>
        /// <param name="sources">Sources.</param>
        /// <returns>Dataset.</returns>
        /// <exception cref="ArgumentNullException">Thrown when sources is null.</exception>
        /// <exception cref="ArgumentException">Thrown when the scale specification is out of range or has no words.</exception>
        public static BenchmarkDataset Synthetic(SyntheticSources sources)
        {
            if (sources == null) throw new ArgumentNullException(nameof(sources));
            IngestScaleSpec spec = sources.IngestScale;
            if (spec.Agents < 1 || spec.Agents > 100000) throw new ArgumentException("ingestScale.agents must be 1 to 100000.", nameof(sources));
            if (spec.Templates < 1 || spec.Templates > 10000) throw new ArgumentException("ingestScale.templates must be 1 to 10000.", nameof(sources));
            if (spec.Words.Count < 4) throw new ArgumentException("ingestScale.words needs at least 4 words.", nameof(sources));
            if (spec.Lanes.Count == 0) throw new ArgumentException("ingestScale.lanes needs at least one lane.", nameof(sources));

            BenchmarkDataset dataset = new BenchmarkDataset();
            dataset.Name = sources.Name;
            dataset.Description = sources.Description;
            dataset.Tier = "synthetic";
            dataset.Source = "Generated by Garrison.Benchmark generate --kind synthetic from benchmarks/datasets/synthetic/sources.json (seed " + spec.Seed.ToString(CultureInfo.InvariantCulture) + ").";
            dataset.Corpora.AddRange(sources.Corpora);

            Random random = new Random(spec.Seed);
            BenchmarkCorpus fleet = new BenchmarkCorpus();
            fleet.Id = spec.CorpusId;
            fleet.Command = "ingest";
            fleet.Description = "A fictional fleet: " + spec.Agents + " agents, each with one fake-harness deployment, sharing " + spec.Templates + " Task prompt templates whose popularity follows a Zipf distribution (exponent " + spec.ZipfExponent.ToString("0.##", CultureInfo.InvariantCulture) + "), pinned to worker lanes by node selector.";
            for (int t = 0; t < spec.Templates; t++)
            {
                string name = "fleet-task-" + t.ToString("D3", CultureInfo.InvariantCulture);
                string words = Words(spec.Words, random, 3);
                StringBuilder yaml = new StringBuilder();
                yaml.Append("apiVersion: garrison/v1\nkind: PromptTemplate\nmetadata:\n  name: ").Append(name).Append('\n');
                yaml.Append("  description: Shared task template ").Append(t.ToString(CultureInfo.InvariantCulture)).Append(" for ").Append(words).Append('\n');
                yaml.Append("spec:\n  kind: Task\n  content: \"[").Append(words).Append("] {{input.message}}\"\n");
                fleet.Items.Add(Item("template-" + t.ToString("D3", CultureInfo.InvariantCulture), "PromptTemplate", name, yaml.ToString()));
            }
            double[] cumulative = Zipf(spec.Templates, spec.ZipfExponent);
            for (int a = 0; a < spec.Agents; a++)
            {
                string agent = "fleet-agent-" + a.ToString("D4", CultureInfo.InvariantCulture);
                string display = Title(Words(spec.Words, random, 2));
                StringBuilder yaml = new StringBuilder();
                yaml.Append("apiVersion: garrison/v1\nkind: Agent\nmetadata:\n  name: ").Append(agent).Append('\n');
                yaml.Append("  description: ").Append(display).Append(" agent of the synthetic fleet\n");
                yaml.Append("spec:\n  displayName: ").Append(display).Append('\n');
                yaml.Append("  tags: [fleet, ").Append(spec.Words[random.Next(spec.Words.Count)]).Append("]\n");
                yaml.Append("  exposure: { a2a: ").Append(random.Next(2) == 0 ? "true" : "false").Append(", mcpTool: ").Append(random.Next(2) == 0 ? "true" : "false").Append(" }\n");
                fleet.Items.Add(Item("agent-" + a.ToString("D4", CultureInfo.InvariantCulture), "Agent", agent, yaml.ToString()));

                int template = Sample(cumulative, random);
                string lane = spec.Lanes[random.Next(spec.Lanes.Count)];
                StringBuilder deployment = new StringBuilder();
                deployment.Append("apiVersion: garrison/v1\nkind: Deployment\nmetadata:\n  name: ").Append(agent).Append("-fake\n");
                deployment.Append("spec:\n  agent: ").Append(agent).Append('\n');
                deployment.Append("  harnessProfile: builtin/fake\n");
                deployment.Append("  timeoutSeconds: ").Append((60 + 30 * random.Next(10)).ToString(CultureInfo.InvariantCulture)).Append('\n');
                deployment.Append("  maxConcurrentRuns: ").Append(random.Next(5).ToString(CultureInfo.InvariantCulture)).Append('\n');
                deployment.Append("  maxAttempts: ").Append((1 + random.Next(3)).ToString(CultureInfo.InvariantCulture)).Append('\n');
                deployment.Append("  prompts:\n    Task: fleet-task-").Append(template.ToString("D3", CultureInfo.InvariantCulture)).Append('\n');
                deployment.Append("  parameters:\n    format: claude\n    delayMs: \"").Append((random.Next(6) * 10).ToString(CultureInfo.InvariantCulture)).Append("\"\n");
                deployment.Append("  nodeSelector:\n    bench.garrison.io/lane: ").Append(lane).Append('\n');
                fleet.Items.Add(Item("deployment-" + a.ToString("D4", CultureInfo.InvariantCulture), "Deployment", agent + "-fake", deployment.ToString()));
            }
            fleet.Probes.AddRange(spec.Probes);
            dataset.Corpora.Add(fleet);
            return dataset;
        }

        /// <summary>
        /// Build the live dataset from the repository files named in the sources.
        /// </summary>
        /// <param name="sources">Sources.</param>
        /// <param name="root">Repository root.</param>
        /// <returns>Dataset.</returns>
        /// <exception cref="ArgumentNullException">Thrown when an argument is null.</exception>
        /// <exception cref="FileNotFoundException">Thrown when a listed file does not exist.</exception>
        /// <exception cref="InvalidDataException">Thrown when a document has no kind or name.</exception>
        public static BenchmarkDataset Live(LiveSources sources, string root)
        {
            if (sources == null) throw new ArgumentNullException(nameof(sources));
            if (root == null) throw new ArgumentNullException(nameof(root));
            List<BenchmarkItem> items = new List<BenchmarkItem>();
            HashSet<string> seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (string file in sources.Files)
            {
                string path = Path.Combine(root, file);
                if (!File.Exists(path)) throw new FileNotFoundException("Live source file not found: " + file, path);
                string text = File.ReadAllText(path).Replace("\r\n", "\n", StringComparison.Ordinal);
                foreach (KeyValuePair<string, string> substitution in sources.Substitutions) text = text.Replace(substitution.Key, substitution.Value, StringComparison.Ordinal);
                List<string> lines = text.Split('\n').Where(l => !sources.DropLinesContaining.Any(d => l.Contains(d, StringComparison.Ordinal))).ToList();
                foreach (string document in Regex.Split(String.Join("\n", lines), "^---\\s*$", RegexOptions.Multiline))
                {
                    string body = Trim(document);
                    if (body.Length == 0) continue;
                    Match kind = Regex.Match(body, "^kind:\\s*(\\S+)\\s*$", RegexOptions.Multiline);
                    Match name = Regex.Match(body, "^metadata:\\s*\\n(?:\\s+#.*\\n)*\\s+name:\\s*\"?([^\"\\s]+)\"?\\s*$", RegexOptions.Multiline);
                    if (!kind.Success || !name.Success) throw new InvalidDataException("A document in " + file + " has no kind or metadata.name.");
                    string id = kind.Groups[1].Value.ToLowerInvariant() + "-" + name.Groups[1].Value;
                    if (!seen.Add(id)) continue;
                    items.Add(Item(id, kind.Groups[1].Value, name.Groups[1].Value, body + "\n"));
                }
            }
            foreach (BenchmarkItem extra in sources.ExtraItems)
            {
                if (seen.Add(extra.Id)) items.Add(extra);
            }

            BenchmarkDataset dataset = new BenchmarkDataset();
            dataset.Name = sources.Name;
            dataset.Description = sources.Description;
            dataset.Tier = "live";
            dataset.SnapshotDate = sources.SnapshotDate;
            dataset.Source = "Frozen snapshot of " + String.Join(", ", sources.Files) + " on " + sources.SnapshotDate + ", substituted as the bootstrap Job does, built by Garrison.Benchmark generate --kind live from benchmarks/datasets/live/sources.json.";
            foreach (BenchmarkCorpus spec in sources.Corpora)
            {
                BenchmarkCorpus corpus = new BenchmarkCorpus();
                corpus.Id = spec.Id;
                corpus.Command = spec.Command;
                corpus.Description = spec.Description;
                corpus.Items.AddRange(items);
                corpus.Probes.AddRange(spec.Probes);
                dataset.Corpora.Add(corpus);
            }
            return dataset;
        }

        /// <summary>
        /// Serialize a dataset the way it is committed: indented JSON, LF line endings, trailing newline.
        /// </summary>
        /// <param name="dataset">Dataset.</param>
        /// <returns>Text.</returns>
        /// <exception cref="ArgumentNullException">Thrown when dataset is null.</exception>
        public static string Serialize(BenchmarkDataset dataset)
        {
            if (dataset == null) throw new ArgumentNullException(nameof(dataset));
            return JsonSerializer.Serialize(dataset, JsonDefaults.Indented).Replace("\r\n", "\n", StringComparison.Ordinal) + "\n";
        }

        #endregion

        #region Private-Methods

        private static BenchmarkItem Item(string id, string kind, string name, string manifest)
        {
            BenchmarkItem item = new BenchmarkItem();
            item.Id = id;
            item.Kind = kind;
            item.Name = name;
            item.Manifest = manifest;
            return item;
        }

        private static string Trim(string document)
        {
            List<string> lines = document.Split('\n').ToList();
            while (lines.Count > 0 && (lines[0].Trim().Length == 0 || lines[0].TrimStart().StartsWith('#'))) lines.RemoveAt(0);
            while (lines.Count > 0 && lines[lines.Count - 1].Trim().Length == 0) lines.RemoveAt(lines.Count - 1);
            return String.Join("\n", lines);
        }

        private static string Words(List<string> words, Random random, int count)
        {
            List<string> picked = new List<string>();
            for (int i = 0; i < count; i++) picked.Add(words[random.Next(words.Count)]);
            return String.Join(" ", picked);
        }

        private static string Title(string text)
        {
            return String.Join(" ", text.Split(' ').Select(w => w.Length == 0 ? w : Char.ToUpperInvariant(w[0]) + w.Substring(1)));
        }

        private static double[] Zipf(int n, double exponent)
        {
            double[] cumulative = new double[n];
            double total = 0;
            for (int k = 1; k <= n; k++)
            {
                total += 1.0 / Math.Pow(k, exponent);
                cumulative[k - 1] = total;
            }
            for (int k = 0; k < n; k++) cumulative[k] /= total;
            return cumulative;
        }

        private static int Sample(double[] cumulative, Random random)
        {
            double u = random.NextDouble();
            for (int k = 0; k < cumulative.Length; k++)
            {
                if (u <= cumulative[k]) return k;
            }
            return cumulative.Length - 1;
        }

        #endregion
    }
}
