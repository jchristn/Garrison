#!/usr/bin/env bash
# Deploys Garrison into the scale-test cluster: SERVERS control-plane replicas on Postgresql, WORKERS fake-harness
# workers with WORKER_CONCURRENCY slots each, and waits until every worker is registered and Ready.
#
#   k8s/tests/deploy.sh                                 # 3 servers, 4 workers, 4 slots each
#   SERVERS=2 WORKERS=6 k8s/tests/deploy.sh             # re-run to resize; secrets and data are kept
#
# Renders k8s/tests/overlay wrapped with the sizes into k8s/tests/.work/deploy (kept for inspection).
# DRY_RUN=1 only renders (no cluster needed) and prints the path of the rendered manifests.
source "$(dirname "$0")/common.sh"
need kubectl
need python3
[ "${DRY_RUN:-0}" = "1" ] || require_cluster

DEPLOY_DIR="${WORK_DIR}/deploy"
mkdir -p "${DEPLOY_DIR}"
OVERLAY_REL="$(python3 -c 'import os,sys; print(os.path.relpath(sys.argv[1], sys.argv[2]))' "${TEST_DIR}/overlay" "${DEPLOY_DIR}")"

cat > "${DEPLOY_DIR}/kustomization.yaml" <<YAML
# Generated by k8s/tests/deploy.sh. Do not edit; re-run the script.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ${OVERLAY_REL}
replicas:
  - name: garrison-server
    count: ${SERVERS}
  - name: garrison-worker
    count: ${WORKERS}
images:
  - name: jchristn77/garrison-server
    newTag: ${IMAGE_TAG}
  - name: jchristn77/garrison-worker
    newTag: ${IMAGE_TAG}
  - name: jchristn77/garrison-dashboard
    newTag: ${IMAGE_TAG}
patches:
  - patch: |-
      apiVersion: apps/v1
      kind: Deployment
      metadata:
        name: garrison-server
      spec:
        template:
          spec:
            containers:
              - name: server
                env:
                  - name: GARRISON_EXPECTED_REPLICAS
                    value: "${SERVERS}"
  - patch: |-
      apiVersion: apps/v1
      kind: StatefulSet
      metadata:
        name: garrison-worker
      spec:
        template:
          spec:
            containers:
              - name: worker
                env:
                  - name: GARRISON_WORKER_MAX_CONCURRENT_RUNS
                    value: "${WORKER_CONCURRENCY}"
YAML

if [ "${DRY_RUN:-0}" = "1" ]; then
  kubectl kustomize "${DEPLOY_DIR}" > "${DEPLOY_DIR}/rendered.yaml"
  log "rendered ${DEPLOY_DIR}/rendered.yaml (${SERVERS} servers, ${WORKERS} workers x ${WORKER_CONCURRENCY}, images ${IMAGE_TAG})"
  exit 0
fi

log "secrets"
KUBECONFIG="${KUBECONFIG_FILE}" GARRISON_NAMESPACE="${NAMESPACE}" "${K8S_DIR}/scripts/generate-secrets.sh" >/dev/null
log "applying ${SERVERS} server(s), ${WORKERS} worker(s) x ${WORKER_CONCURRENCY} slots, images ${IMAGE_TAG}"
kc kustomize "${DEPLOY_DIR}" > "${DEPLOY_DIR}/rendered.yaml"
kc apply -f "${DEPLOY_DIR}/rendered.yaml" >/dev/null

kcn rollout status statefulset/garrison-postgres --timeout=300s
kcn rollout status deployment/garrison-server --timeout=600s
kcn rollout status statefulset/garrison-worker --timeout=600s
kcn wait --for=condition=complete job/garrison-bootstrap --timeout=300s >/dev/null 2>&1 \
  || log "bootstrap Job not complete (not needed by the tests): kubectl --kubeconfig ${KUBECONFIG_FILE} -n ${NAMESPACE} logs job/garrison-bootstrap"

KEY="$(admin_key)"
log "waiting for ${WORKERS} Ready workers at ${BASE_URL}"
ready=0
for i in $(seq 1 120); do
  ready=$(curl -fsS -H "x-api-key: ${KEY}" "${BASE_URL}/v1.0/api/nodes?maxResults=1000" 2>/dev/null \
    | grep -o '"status":"Ready"' | wc -l | tr -d ' ' || true)
  [ "${ready:-0}" -ge "${WORKERS}" ] && break
  sleep 2
done
[ "${ready:-0}" -ge "${WORKERS}" ] || fail "only ${ready:-0} of ${WORKERS} workers are Ready"
kcn get pods -o wide
log "deployed. next: k8s/tests/loadtest.sh, rolling-upgrade-test.sh, or chaos-test.sh"
